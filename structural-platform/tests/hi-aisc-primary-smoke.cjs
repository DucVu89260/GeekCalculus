const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.HI_BASE_URL || 'http://127.0.0.1:5192/hi-doubly-symmetric-aisc360-10.html'

;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => localStorage.setItem('geekcalculus-locale', 'en'))
    await page.goto(base)
    await page.waitForFunction(() => typeof verifiedResult !== 'undefined' && verifiedResult?.classification)
    assert.equal(await page.locator('#calculation-mode').inputValue(), 'AISC36010')
    assert.match(await page.locator('#calc-info').innerText(), /AISC 360-10/)
    assert.doesNotMatch(await page.locator('#warnings').innerText(), /LEGACY_EDITION|LEGACY_CB|LEGACY_WEAK_AXIS_FE|STIFFENER_PARITY_ONLY/)
    assert.equal(await page.locator('#calculation-notebook').isVisible(), false)
    assert.equal(await page.locator('#h1').innerText(), '—', 'missing independent restraint data blocks H1')
    await page.locator('[data-tab="member"]').click()
    for (const [id, value] of Object.entries({ 'aisc-kx': 1, 'aisc-ky': 1, 'aisc-ly': 4000, 'aisc-kz': 1, 'aisc-lz': 4000, 'aisc-g': 77000 })) {
      await page.locator(`#${id}`).fill(String(value))
    }
    await page.locator('#run').click()
    await page.waitForFunction(() => verifiedResult?.limit_states.compression.status === 'CALCULATED')
    const lrfd = await page.evaluate(() => structuredClone(verifiedResult))
    const trace = lrfd.limit_states.compression.trace
    assert.notEqual(trace.fex_mpa, trace.fey_mpa, 'weak-axis Euler stress must be independent')
    assert.equal(lrfd.limit_states.major_flexure.trace.cb, 1, 'conservative Cb has no unconfirmed extrema')
    assert.equal(lrfd.limit_states.shear_web.available, undefined)
    assert.equal(lrfd.limit_states.stiffeners.status, 'REVIEW_REQUIRED')
    assert.doesNotMatch(await page.locator('#checkrows').innerText(), /\bPASS\b/)
    await page.locator('input[name="design-method"][value="ASD"]').check()
    await page.waitForFunction(() => verifiedResult?.mode === 'ASD')
    const asd = await page.evaluate(() => structuredClone(verifiedResult))
    assert.equal(asd.limit_states.compression.nominal, lrfd.limit_states.compression.nominal)
    assert.ok(Math.abs(asd.limit_states.compression.available - asd.limit_states.compression.nominal / 1.67) < 1e-9)
    const downloadEvent = page.waitForEvent('download')
    await page.locator('#export').click()
    const download = await downloadEvent
    const output = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
    assert.equal(output.meta.mode, 'AISC36010_REFERENCE')
    assert.equal(output.result.mode, 'ASD')
    assert.equal(output.result.overall_status, 'REVIEW_REQUIRED')
    assert.ok(output.legacy_comparison, 'legacy data is named explicitly')
    await page.locator('#aisc-kx').fill('2')
    assert.equal(await page.locator('#h1').innerText(), '—', 'dirty bracing invalidates the displayed ratio')
    await page.locator('#run').click()
    await page.waitForFunction(() => verifiedResult?.mode === 'ASD')
    await page.locator('[data-tab="geometry"]').click()
    await page.locator('[data-key="h_mm"]').fill('')
    await page.locator('#run').click()
    assert.equal(await page.locator('#h1').innerText(), '—', 'invalid geometry must not restore a stale result')
    assert.equal(await page.evaluate(() => verifiedResult), null)
    await page.locator('#preset').click()
    await page.locator('#calculation-mode').selectOption('LEGACY')
    await page.waitForFunction(() => document.getElementById('warnings').textContent.includes('LEGACY_WEAK_AXIS_FE'))
    assert.equal(await page.locator('#calculation-notebook').isVisible(), true)
    assert.equal(await page.locator('#h1').innerText(), '82.41%')
    await page.locator('#calculation-mode').selectOption('AISC36010')
    await page.waitForFunction(() => verifiedResult?.mode === 'LRFD')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('Symmetric I/H primary AISC kernel, separate legacy comparison, ASD factors, missing-check barriers, stale input rejection, export and mobile smoke passed. This is not private-source engineering approval.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
