// Requires engineering/tests/sap_panel_server.py: multi-model fake SAP on port 8011.
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 }, acceptDownloads: true })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const headers = { Authorization: 'Bearer sap-panel-browser-test-token-00000001' }
    const base = 'http://127.0.0.1:8011/API_IF_SAP26.2.0_V1'
    await page.request.put(base+'/connection', { headers, data: { pid: null } })
    await page.goto('http://127.0.0.1:8011/#token=sap-panel-browser-test-token-00000001')
    await page.waitForFunction(() => document.querySelectorAll('#instance option').length === 4 && !document.querySelector('#controls').disabled)
    assert.equal(new URL(page.url()).hash, '')
    assert.equal(await page.locator('#token-entry').isVisible(), false)
    assert.equal(await page.locator('#instance').inputValue(), '')
    assert.equal(await page.locator('#connect').isDisabled(), true)
    assert.equal(await page.locator('#instance option[value="56789"]').isDisabled(), true)
    assert.match(await page.locator('#instance-errors').textContent(), /56789/)
    assert.match(await page.locator('#instance option[value="34567"]').textContent(), /Tower B.sdb.*34567/)
    await page.locator('#instance').selectOption('34567')
    await page.locator('#connect').click()
    await page.waitForFunction(() => document.querySelector('#filename').textContent === 'Tower B.sdb' && !document.querySelector('#controls').disabled)
    assert.equal(await page.locator('#detected-pid').textContent(), '34567')
    let cfg = await (await page.request.get(base+'/connection', { headers })).json()
    assert.equal(cfg.pid, 34567)
    assert.equal(cfg.expected_model, 'C:\\Models\\Tower B.sdb')
    await page.locator('#instance').selectOption('20948')
    assert.equal(await page.locator('#filename').textContent(), 'Chưa kết nối')
    await page.locator('#connect').click()
    await page.waitForFunction(() => document.querySelector('#filename').textContent === 'Tower A.sdb' && !document.querySelector('#controls').disabled)
    await page.reload()
    await page.waitForFunction(() => document.querySelector('#filename').textContent === 'Tower A.sdb' && !document.querySelector('#controls').disabled)
    assert.equal(await page.locator('#instance').inputValue(), '20948')
    assert.equal(await page.locator('#token-entry').isVisible(), false)
    await page.locator('#cases label').filter({ hasText: 'DEAD' }).locator('input').check()
    await page.locator('#cases label').filter({ hasText: 'ULS' }).locator('input').check()
    await page.locator('#selection').click()
    await page.waitForFunction(() => document.querySelector('#frames').textContent.includes('F1, F2'))
    await page.locator('#extract').click()
    await page.waitForFunction(() => document.querySelectorAll('#results tr').length === 8)
    assert.match(await page.locator('#snapshot').textContent(), /Tower A.sdb.*8 dòng/)
    await page.locator('#extremes').click()
    await page.waitForFunction(() => document.querySelectorAll('#extreme-results tr').length === 12)
    const jsonDownload = page.waitForEvent('download')
    await page.locator('#json').click()
    assert.equal((await jsonDownload).suggestedFilename(), 'sap2000-forces.json')
    const csvDownload = page.waitForEvent('download')
    await page.locator('#csv').click()
    assert.equal((await csvDownload).suggestedFilename(), 'sap2000-connection-forces.csv')
    await page.waitForFunction(() => !document.querySelector('#controls').disabled)
    await page.locator('#select-none').click()
    await page.locator('#cases label').filter({ hasText: 'ENV' }).locator('input').check()
    await page.locator('#extract').click()
    await page.waitForFunction(() => document.querySelector('#results td:nth-child(4)')?.textContent === 'ENV')
    await page.locator('#csv').click()
    await page.waitForFunction(() => document.querySelector('#status').classList.contains('error') && !document.querySelector('#controls').disabled)
    assert.match(await page.locator('#status').textContent(), /Envelope/)
    await page.locator('#instance').selectOption('34567')
    assert.equal(await page.locator('#results tr').count(), 0)
    assert.equal(await page.locator('#extreme-results tr').count(), 0)
    assert.equal(await page.locator('#csv').isDisabled(), true)
    await page.locator('#scan').click()
    await page.waitForFunction(() => document.querySelectorAll('#instance option').length === 4 && !document.querySelector('#controls').disabled)
    assert.equal(await page.locator('#instance').inputValue(), '34567')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('SAP panel smoke passed: multi-model discovery, PID/file selection, failed PID, switching/reset, extraction, exports, extremes, mobile.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
