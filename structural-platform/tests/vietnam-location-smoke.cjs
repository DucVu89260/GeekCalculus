// Native mode uses a read-only synthetic session: this checks UI, not backend auth.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/opt/codex/cua_node/lib/node_modules/playwright')
const { signIn } = require('./browser-auth.cjs')
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../standards/qcvn02-2022-locations.json'), 'utf8'))
const base = process.env.VN_BASE_URL || 'http://127.0.0.1:8821/GeekCalculus/'
const demo = process.env.TEST_DEMO !== '0'
const route = name => `${base}#/modules/${name}`
const seismic = (province, label) => data.seismic.find(r => r.province_id === province && r.location === label)
const wind = (province, prefix) => data.wind.find(r => r.province_id === province && r.location.startsWith(prefix))

;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    if (!demo) await page.route('**/api/auth/me', r => r.fulfill({ json: { user: { id: 9001, role: 'user', name: 'UI fixture' } } }))
    await page.goto(base)
    if (demo) await signIn(page, { demo: true, role: 'user' })
    if (demo) {
      await page.goto(route('steel/library'))
      await page.locator('.vn-library-entry a').click()
    } else await page.goto(route('steel/library/vietnam-location'))
    await page.locator('.vn-lookup').waitFor()
    await page.locator('.module-topbar .language-switch').getByRole('button', { name: 'VI', exact: true }).click()
    assert.equal(await page.locator('[data-vn="province"] option').count(), 64)
    assert.equal(await page.locator('[data-vn-value="w0"]').count(), 0)
    await page.locator('[data-vn="province"]').selectOption('p01')
    await page.getByRole('img', { name: 'Gió tác dụng lên công trình', exact: true }).waitFor()
    await page.getByRole('img', { name: 'Gia tốc nền tham chiếu aɡR', exact: true }).waitFor()
    await page.locator('[data-vn="wind"]').selectOption(wind('p01', 'Huyện Mỹ Đức (xã').id)
    await page.locator('[data-vn="seismic"]').selectOption(seismic('p01', 'Huyện Mỹ Đức').id)
    assert.match(await page.locator('[data-vn-value="w0"]').innerText(), /125.*daN\/m²/s)
    assert.match(await page.locator('[data-vn-value="agr"]').innerText(), /0,10.*g/s)
    assert.match(await page.locator('[data-vn-value="ss"]').innerText(), /0,37.*g/s)
    assert.match(await page.locator('[data-vn-value="s1"]').innerText(), /0,15.*g/s)
    assert.match(await page.locator('.vn-scope').first().innerText(), /xã Hương Sơn/)
    assert.match(await page.locator('.vn-lookup').innerText(), /500 năm/)
    assert.match(await page.locator('.vn-lookup').innerText(), /2.500 năm/)
    const hrefs = await page.locator('.vn-page-link').evaluateAll(a => a.map(e => e.href))
    assert.ok(hrefs.some(h => h.endsWith('#page=43')))
    assert.ok(hrefs.some(h => h.endsWith('#page=71')))
    assert.ok(hrefs.some(h => h.endsWith('#page=88')))
    assert.equal(await page.locator('.module-navigation a[aria-current="page"]').innerText(), 'Steel Library')
    const exportJson = async () => {
      const download = page.waitForEvent('download')
      await page.locator('.vn-header button').click()
      return JSON.parse(fs.readFileSync(await (await download).path(), 'utf8'))
    }
    const vi = await exportJson()
    await page.locator('.module-topbar .language-switch').getByRole('button', { name: 'EN', exact: true }).click()
    assert.match(await page.locator('.vn-header h2').innerText(), /Vietnam location lookup/)
    await page.getByRole('img', { name: 'Wind acting on a structure', exact: true }).waitFor()
    await page.getByRole('img', { name: 'Reference ground acceleration aɡR', exact: true }).waitFor()
    assert.match(await page.locator('[data-vn-value="agr"]').innerText(), /0.10.*g/s)
    assert.deepEqual(await exportJson(), vi)
    assert.equal(vi.independent_source_selections, true)
    assert.equal(vi.units.ss, 'g')
    await page.reload()
    await page.locator('.vn-lookup').waitFor()
    await page.locator('[data-vn="province"]').selectOption('p04')
    await page.locator('[data-vn="search"]').fill('cam le')
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 9) // Draft is not applied yet.
    await page.locator('[data-vn="search"]').press('Enter')
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 2)
    assert.equal(await page.locator('[data-vn="wind"] option').count(), 1)
    await page.locator('[data-vn="seismic"]').selectOption(seismic('p04', 'Quận Cẩm Lệ').id)
    assert.match(await page.locator('[data-vn-value="agr"]').innerText(), /0.04.*g/s)
    await page.locator('[data-vn="search-clear"]').click()
    assert.equal(await page.locator('[data-vn="province"] option').count(), 64)
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 9)
    assert.equal(await page.locator('[data-vn="seismic"]').inputValue(), seismic('p04', 'Quận Cẩm Lệ').id)
    await page.locator('[data-vn="province"]').selectOption('')
    await page.locator('[data-vn="search"]').fill('Cu Chi')
    await page.locator('[data-vn="search-submit"]').click()
    assert.equal(await page.locator('[data-vn="province"] option').count(), 2)
    await page.locator('[data-vn="province"]').selectOption('p02')
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 2)
    await page.locator('[data-vn="seismic"]').selectOption(seismic('p02', 'Huyện Củ Chi').id)
    assert.equal(await page.locator('[data-vn="province"]').inputValue(), 'p02')
    assert.match(await page.locator('[data-vn-value="agr"]').innerText(), /0.06.*g/s)
    await page.locator('[data-vn="search"]').fill('unknownxyz')
    await page.locator('[data-vn="search-submit"]').click()
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 1)
    assert.equal(await page.locator('[data-vn="seismic"]').inputValue(), '')
    assert.equal(await page.locator('[data-vn-value="agr"]').count(), 0)
    assert.ok(await page.locator('.vn-header button').isDisabled())
    await page.locator('[data-vn="search-clear"]').click()
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 23)
    await page.locator('[data-vn="province"]').selectOption('p41')
    assert.equal(await page.locator('[data-vn="wind"]').inputValue(), '')
    assert.equal(await page.locator('[data-vn="seismic"]').inputValue(), '')
    await page.locator('[data-vn="seismic"]').selectOption(seismic('p41', 'Thành phố Vinh').id)
    assert.match(await page.locator('[data-vn-value="ss"]').innerText(), /Unit unconfirmed/)
    assert.equal((await exportJson()).seismic_location.ss.value_g, null)
    assert.match(await page.locator('.vn-lookup').innerText(), /0,38/)
    await page.locator('[data-vn="province"]').selectOption('p59')
    await page.locator('[data-vn="seismic"]').selectOption(seismic('p59', 'Huyện Duyên Hải').id)
    assert.match(await page.locator('.vn-note').innerText(), /shared/)
    await page.locator('[data-vn="search"]').fill('unknownxyz')
    await page.locator('[data-vn="search-submit"]').click()
    assert.equal(await page.locator('[data-vn="wind"] option').count(), 1)
    assert.equal(await page.locator('[data-vn="seismic"] option').count(), 1)
    await page.locator('[data-vn="search"]').fill('')
    await page.waitForFunction(() => document.querySelectorAll('[data-vn="province"] option').length === 64)
    await page.locator('[data-vn="province"]').selectOption('p01')
    await page.locator('[data-vn="wind"]').selectOption(wind('p01', 'Huyện Ứng Hoà (thị trấn').id)
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 880 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `overflow ${width}`)
    }
    await page.screenshot({ path: `/tmp/vietnam-lookup-${demo ? 'demo' : 'native'}-mobile.png`, fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1080 })
    await page.locator('[data-vn="seismic"]').selectOption(seismic('p01', 'Quận Ba Đình').id)
    await page.screenshot({ path: `/tmp/vietnam-lookup-${demo ? 'demo' : 'native'}-desktop.png`, fullPage: true })
    if (demo) {
      await page.locator('.vn-header a').click()
      await page.locator('.library-browser').waitFor()
      assert.equal(await page.locator('.library-tabs button[role="tab"]').count(), 3)
      await page.goto(route('concrete/library'))
      await page.locator('.library-browser').waitFor()
      assert.equal(await page.locator('.vn-library-entry').count(), 0)
    }
    assert.deepEqual(errors, [])
    console.log(`PASS ${demo ? 'demo' : 'native (synthetic read-only session)'}: lookup, units, scope, source pages, VI/EN JSON parity, missing-source unit, search, reload and mobile`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
