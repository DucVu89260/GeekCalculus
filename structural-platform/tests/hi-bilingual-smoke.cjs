const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/opt/codex/cua_node/lib/node_modules/playwright')
const base = process.env.HI_BASE_URL || 'http://127.0.0.1:5173/hi-doubly-symmetric-aisc360-10.html'

async function main() {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  try {
    const page = await browser.newPage()
    page.setDefaultTimeout(15000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base)
    await page.locator('#calculation-mode').selectOption('LEGACY')
    await page.waitForFunction(() => document.querySelector('#h1').textContent === '82.41%', null, { timeout: 10000 })
    assert.equal(await page.locator('html').getAttribute('lang'), 'en')
    const snapshot = () => page.evaluate(() => ({ input: latest.input, result: latest.result, dirty: latest.changed }))
    for (const label of ['VN', 'ENG']) assert.ok(await page.getByRole('button', { name: label, exact: true }).isVisible())
    assert.equal(await page.locator('.intro-actions .language-switch').count(), 1)
    const initial = await snapshot()
    assert.equal(initial.result.section_properties.area_mm2, 11496)
    assert.ok(Math.abs(initial.result.interaction.lrfd_percent - 82.40656143563768) < 1e-6)
    await page.locator('#steps-expand').click()
    const english = await page.locator('body').innerText()
    assert.ok(english.includes('Axial compressive resistance'))
    assert.ok(!/[ăâđêôơư\u1ea0-\u1ef9]/i.test(english), 'English view contains untranslated Vietnamese')
    for (let i = 0; i < 2; i++) {
      await page.locator('[data-locale="vi"]').click()
      assert.equal(await page.locator('html').getAttribute('lang'), 'vi')
      assert.equal(await page.locator('#status').textContent(), 'CẦN RÀ SOÁT')
      assert.equal(await page.locator('.language-switch').getAttribute('aria-label'), 'Ngôn ngữ')
      assert.equal(await page.locator('[data-key="h_mm"]').locator('..').innerText(), 'Chiều cao toàn bộ\nh')
      assert.ok((await page.locator('#warnings').innerText()).includes('không phải AISC 360-10'))
      assert.ok((await page.locator('#step-content').innerText()).includes('Sức kháng nén dọc trục'))
      assert.equal(await page.locator('.step-table td').first().getAttribute('data-label'), 'Thông số')
      assert.deepEqual(await snapshot(), initial)
      await page.locator('[data-locale="en"]').click()
      assert.equal(await page.locator('#status').textContent(), 'REVIEW REQUIRED')
      assert.equal(await page.locator('body').innerText(), english)
    }
    await page.locator('[data-key="h_mm"]').fill('960')
    const dirty = await snapshot()
    assert.equal(dirty.dirty, true)
    await page.locator('[data-locale="vi"]').click()
    assert.deepEqual(await snapshot(), dirty)
    assert.ok((await page.locator('#dirtytext').innerText()).includes('Nhấn Tính toán'))
    await page.locator('#run').click()
    assert.equal((await snapshot()).dirty, false)
    assert.notEqual((await snapshot()).result.section_properties.area_mm2, 11496)
    await page.locator('[data-key="h_mm"]').fill('')
    await page.locator('#run').click()
    assert.ok((await page.locator('#error').innerText()).includes('Vui lòng nhập giá trị số'))
    await page.locator('[data-locale="en"]').click()
    assert.ok((await page.locator('#error').innerText()).includes('Please enter a numeric value'))
    assert.equal(await page.locator('[data-key="h_mm"]').inputValue(), '')
    await page.locator('#preset').click()
    await page.locator('[data-locale="vi"]').click()
    await page.locator('#file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
    await page.waitForFunction(() => document.querySelector('#error').textContent.includes('Nhập JSON thất bại'), null, { timeout: 10000 })
    await page.locator('#preset').click()
    await page.evaluate(() => { navigator.clipboard.writeText = async text => { window.copiedReport = text } })
    await page.locator('#steps-copy').click()
    assert.ok((await page.evaluate(() => window.copiedReport)).includes('Sức kháng nén dọc trục'))
    await page.reload()
    await page.locator('#calculation-mode').selectOption('LEGACY')
    assert.equal(await page.locator('html').getAttribute('lang'), 'vi')
    await page.setViewportSize({ width: 390, height: 844 })
    for (const label of ['VN', 'ENG']) assert.ok(await page.getByRole('button', { name: label, exact: true }).isVisible())
    await page.locator('#steps-expand').click()
    assert.equal(await page.locator('.step-table td').first().getAttribute('data-label'), 'Thông số')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflows horizontally')
    const downloadEvent = page.waitForEvent('download')
    await page.locator('#export').click()
    const download = await downloadEvent
    const output = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
    assert.deepEqual(output.input, initial.input)
    assert.deepEqual(output.result, initial.result)
    assert.equal(output.result.overall_status, 'REVIEW_REQUIRED')
    assert.deepEqual(errors, [])
    const source = fs.readFileSync(path.join(__dirname, '../frontend/vue/public/hi-doubly-symmetric-aisc360-10.html'))
    const publishedDir = process.env.HI_PUBLISHED_DIR || path.join(__dirname, '../../docs')
    assert.deepEqual(source, fs.readFileSync(path.join(publishedDir, 'hi-doubly-symmetric-aisc360-10.html')))
    console.log('Symmetric I/H bilingual checks passed: EN/VI round-trip, numeric parity, dirty inputs, validation, JSON import/export, copied report, persistence, mobile labels and published copy.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
