const assert = require('node:assert/strict')
const { signIn } = require('./browser-auth.cjs')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
  try {
    const context = await browser.newContext()
    const page = await context.newPage()
    const errors = [], apiRequests = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()) })
    const url = process.env.DEMO_BASE_URL || 'http://127.0.0.1:8765/GeekCalculus/'
    await page.goto(url)
    await signIn(page, { demo: true })
    await page.getByRole('note').filter({ hasText: 'Bản demo web' }).waitFor()
    await page.getByText('Demo trên trình duyệt').first().waitFor()
    await page.getByRole('button', { name: 'EN', exact: true }).click()
    await page.getByRole('note').filter({ hasText: 'Web demo' }).waitFor()
    assert.equal(await page.locator('.module-card').count(), 6)
    await page.getByRole('button', { name: 'New project', exact: true }).click()
    await page.locator('select').nth(1).locator('option').filter({ hasText: /^RC beam$/ }).waitFor({ state: 'attached' })
    await page.locator('input[name="name"]').fill('Online demo office')
    await page.getByRole('button', { name: /Create project/ }).click()
    await page.getByText('Online demo office', { exact: true }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: 'Projects', exact: true }).click()
    await page.getByText('Online demo office', { exact: true }).waitFor()
    assert.equal(await page.locator('html').getAttribute('lang'), 'en')
    await page.getByRole('button', { name: 'VI', exact: true }).click()
    await page.getByRole('heading', { name: 'GeekCalculus', exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow')
    const otherContext = await browser.newContext()
    const otherPage = await otherContext.newPage()
    await otherPage.goto(url)
    await signIn(otherPage, { demo: true })
    await otherPage.getByRole('button', { name: 'Dự án', exact: true }).click()
    await otherPage.getByText('Chưa có dự án nào', { exact: true }).waitFor()
    assert.equal(apiRequests.length, 0, 'Static demo attempted server API requests')
    assert.equal(errors.length, 0, errors.join('\n'))
    console.log('Web demo passed: Pages base path/assets, VI/EN catalog, save/reload, independent browser storage, mobile, zero API requests and zero browser exceptions.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
