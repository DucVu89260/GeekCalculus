const assert = require('node:assert/strict')
const fs = require('node:fs')
const crypto = require('node:crypto')
const connectionRegistry = require('../connection-catalog/connection-registry.json')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const { signIn } = require('./browser-auth.cjs')
const demo = process.env.TEST_DEMO === '1'
const base = process.env.MODULE_BASE_URL || 'http://127.0.0.1:5173'
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
  const page = await context.newPage()
  const errors = []
  context.on('page', p => p.on('pageerror', error => errors.push(error.message)))
  page.on('pageerror', error => errors.push(error.message))
  await context.addInitScript(() => { if (!['http:', 'https:'].includes(location.protocol)) return; if (!localStorage.getItem('geekcalculus-locale')) localStorage.setItem('geekcalculus-locale', 'en') })
  async function navyHover(target, textTarget = target) {
    await target.hover()
    await target.evaluate(async element => { await Promise.all(element.getAnimations({ subtree: true }).filter(animation => animation.constructor.name === 'CSSTransition').map(animation => animation.finished.catch(() => {}))) })
    assert.equal(await target.evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(35, 57, 93)')
    assert.equal(await textTarget.evaluate(element => getComputedStyle(element).color), 'rgb(255, 255, 255)')
  }
  try {
    await page.goto(base)
    await page.getByRole('heading', { name: 'Sign in', exact: true }).waitFor()
    const background = await page.locator('.login-visual').evaluate(element => getComputedStyle(element).backgroundImage)
    assert.ok(background.includes('structural-hero.jpg'))
    const response = await page.request.get(new URL('structural-hero.jpg', base).href)
    assert.equal(response.status(), 200)
    assert.ok(response.headers()['content-type'].includes('image/jpeg'))
    const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
    assert.equal(digest(await response.body()), digest(fs.readFileSync('frontend/vue/public/structural-hero.jpg')))
    await page.screenshot({ path: '/tmp/geekcalculus-new-cover.png', fullPage: true })
    await signIn(page, { demo })
    assert.equal(await page.locator('.module-card').count(), 5)
    const steelLink = page.getByRole('link', { name: /Steel design/i })
    await navyHover(steelLink, steelLink.locator('strong'))
    assert.equal(await steelLink.getAttribute('target'), '_blank')
    const newPage = context.waitForEvent('page')
    await steelLink.click()
    const moduleTab = await newPage
    await moduleTab.getByRole('tab', { name: /^Component/ }).waitFor()
    assert.equal(await moduleTab.evaluate(() => window.opener), null)
    assert.equal(await moduleTab.locator('.module-navigation a').count(), 5)
    assert.equal(await moduleTab.locator('.module-navigation a[href$="/modules/analysis"]').count(), 0)
    assert.equal(await page.locator('.module-card[href$="/modules/analysis"]').count(), 0)
    const componentNames = ['Symmetric I/H', 'Asymmetric I/H', 'Channel', 'Angle', 'Tee', 'Double Angle', 'Circle', 'CHS', 'RHS/SHS']
    const componentCards = moduleTab.locator('.steel-component-card')
    assert.deepEqual(await componentCards.locator('strong').allTextContents(), componentNames)
    assert.equal(await componentCards.locator('svg[role="img"]').count(), 9)
    const imagePaths = await componentCards.locator('.section-geometry-thumbnail svg').evaluateAll(images => images.map(image => image.querySelector('path.section-geometry-outline')?.getAttribute('d') ?? image.querySelector('circle.section-geometry-outline')?.outerHTML))
    assert.equal(new Set(imagePaths).size, 8, 'Circle and CHS share the outer circle; other illustrations must be distinct')
    assert.equal(await componentCards.nth(7).locator('circle.section-geometry-hole').count(), 1, 'CHS illustration has a hollow core')
    assert.equal(await componentCards.nth(8).locator('rect.section-geometry-hole').count(), 1, 'RHS/SHS illustration has a hollow core')
    for (const name of componentNames) {
      await moduleTab.getByRole('button', { name, exact: true }).click()
      await moduleTab.locator('.steel-component-workspace').getByRole('heading', { name, exact: true }).waitFor()
      assert.equal(await moduleTab.locator('.steel-component-card[aria-pressed="true"]').count(), 1)
    }
    await navyHover(componentCards.first(), componentCards.first().locator('strong'))
    await moduleTab.getByRole('button', { name: 'Double Angle', exact: true }).focus()
    await moduleTab.keyboard.press('Enter')
    await moduleTab.locator('.steel-component-workspace').getByRole('heading', { name: 'Double Angle', exact: true }).waitFor()
    await moduleTab.getByRole('tab', { name: /^Connection/ }).click()
    await navyHover(moduleTab.getByRole('tab', { name: /^Connection/ }), moduleTab.getByRole('tab', { name: /^Connection/ }).locator('strong'))
    const connectionMenu = moduleTab.locator('.steel-connection-menu')
    await connectionMenu.waitFor({ state: 'visible' })
    assert.equal(await connectionMenu.locator('.connection-group-tab').count(), 2)
    const ids = connectionRegistry.connections.map(entry => entry.id)
    assert.equal(new Set(ids).size, ids.length, 'Connection IDs must be stable and unique')
    const sourceIds = new Set(connectionRegistry.sources.map(entry => entry.id))
    for (const entry of connectionRegistry.connections) {
      assert.ok(connectionRegistry.families.some(family => family.id === entry.family && family.group === entry.group))
      assert.ok(entry.source_ids.every(id => sourceIds.has(id)), `Unknown reference for ${entry.id}`)
      assert.equal(entry.reference_review, 'pending_primary_sources')
    }
    for (const group of connectionRegistry.groups) {
      await connectionMenu.locator(`[data-group="${group.id}"]`).click()
      const cards = connectionMenu.locator('.connection-type-card')
      const expected = connectionRegistry.connections.filter(entry => entry.group === group.id)
      assert.deepEqual((await cards.evaluateAll(elements => elements.map(element => element.dataset.connection))).sort(), expected.map(entry => entry.id).sort())
      assert.equal(await cards.locator('svg[role="img"]').count(), expected.length)
      for (const entry of expected) {
        await connectionMenu.locator(`button[data-connection="${entry.id}"]`).click()
        await connectionMenu.locator(`.connection-workspace[data-connection="${entry.id}"]`).getByRole('heading', { name: entry.name_en, exact: true }).waitFor()
        assert.equal(await connectionMenu.locator('.connection-type-card[aria-pressed="true"]').count(), 1)
      }
    }
    await connectionMenu.locator('[data-group="anchorage"]').click()
    const connectionSearch = connectionMenu.getByRole('searchbox')
    await connectionSearch.fill('hoa chat')
    assert.deepEqual(await connectionMenu.locator('.connection-type-card').evaluateAll(elements => elements.map(element => element.dataset.connection)), ['adhesive_anchor'])
    await connectionMenu.locator('button[data-connection="adhesive_anchor"]').focus()
    await moduleTab.keyboard.press('Enter')
    await connectionMenu.locator('.connection-workspace[data-connection="adhesive_anchor"]').waitFor()
    await connectionSearch.fill('zzzz-no-matching-connection')
    await connectionMenu.getByText('No connection types match this search.', { exact: true }).waitFor()
    await connectionSearch.fill('')
    await connectionMenu.locator('[data-group="steel"]').focus()
    await moduleTab.keyboard.press('Space')
    const lastSteel = connectionRegistry.connections.filter(entry => entry.group === 'steel').at(-1)
    assert.equal(await connectionMenu.locator('.connection-workspace').getAttribute('data-connection'), lastSteel.id)
    await connectionMenu.locator('[data-group="anchorage"]').click()
    assert.equal(await connectionMenu.locator('.connection-workspace').getAttribute('data-connection'), 'adhesive_anchor')
    await moduleTab.setViewportSize({ width: 390, height: 844 })
    assert.ok(await moduleTab.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Connection mobile layout overflows')
    await connectionMenu.locator('.connection-group-tabs').scrollIntoViewIfNeeded()
    await moduleTab.screenshot({ path: '/tmp/geekcalculus-connection-mobile.png' })
    await moduleTab.setViewportSize({ width: 1440, height: 1100 })
    await connectionMenu.locator('.connection-group-tabs').scrollIntoViewIfNeeded()
    await moduleTab.screenshot({ path: '/tmp/geekcalculus-connection-desktop.png' })
    await moduleTab.getByRole('button', { name: 'VI', exact: true }).click()
    await connectionMenu.getByRole('button', { name: /Bu-lông neo & chân cột/ }).waitFor()
    assert.equal(await connectionMenu.locator('.connection-workspace').getAttribute('data-connection'), 'adhesive_anchor')
    await moduleTab.getByRole('tab', { name: /^Component/ }).click()
    await moduleTab.getByRole('tab', { name: /^Connection/ }).click()
    assert.equal(await connectionMenu.locator('.connection-workspace').getAttribute('data-connection'), 'adhesive_anchor')
    await moduleTab.getByRole('tab', { name: /^Component/ }).click()
    assert.equal(await moduleTab.getByRole('button', { name: 'Double Angle', exact: true }).getAttribute('aria-pressed'), 'true')
    await moduleTab.locator('.steel-component-workspace').getByText('Chức năng này đang được phát triển.', { exact: true }).waitFor()
    await moduleTab.getByRole('button', { name: 'EN', exact: true }).click()
    await moduleTab.evaluate(async () => { await Promise.all(document.getAnimations().filter(animation => animation.constructor.name === 'CSSTransition').map(animation => animation.finished.catch(() => {}))) })
    await moduleTab.screenshot({ path: '/tmp/geekcalculus-steel-design.png', fullPage: true })
    await moduleTab.setViewportSize({ width: 390, height: 844 })
    assert.ok(await moduleTab.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Module mobile layout overflows')
    await moduleTab.screenshot({ path: '/tmp/geekcalculus-steel-mobile.png', fullPage: true })
    for (const code of ['concrete', 'loads', 'future']) {
      await moduleTab.locator(`.module-navigation a[href$="/modules/${code}"]`).click()
      await moduleTab.getByLabel(/^Select a tool/).selectOption({ index: 1 })
      await moduleTab.getByRole('status').filter({ hasText: 'awaiting implementation' }).waitFor()
    }
    const profileIds = ['rectangle', 'circle', 'chs', 'shs_rhs', 'symmetric_i', 'asymmetric_i', 'channel', 'angle', 'tee', 'double_angle']
    for (const code of ['steel', 'concrete']) {
      await moduleTab.locator(`.module-navigation a[href$="/modules/${code}"]`).click()
      if (code === 'steel') await moduleTab.getByRole('tab', { name: /^Section properties/ }).click()
      if (code === 'concrete') await moduleTab.getByRole('tab', { name: 'Section properties', exact: true }).click()
      const panel = moduleTab.locator('.section-properties-panel')
      await panel.waitFor({ state: 'visible' })
      assert.equal(await moduleTab.locator('.geometry-workbench').count(), 0, 'Only the shared calculator should be live.')
      const profileSelect = panel.locator('select').first()
      assert.deepEqual(await profileSelect.locator('option').evaluateAll(options => options.map(option => option.value)), profileIds)
      await profileSelect.selectOption('chs')
      await panel.locator('input[name="dimension-diameter"]').fill('100')
      await panel.locator('input[name="dimension-thickness"]').fill('5')
      const result = panel.locator('.section-calculated-properties')
      await result.waitFor({ state: 'visible' })
      await result.locator('details.section-calculated-formula-report > summary').waitFor({ state: 'visible' })
      const areaRow = result.getByText('A · Area', { exact: true }).locator('..')
      await result.getByLabel('Display unit', { exact: true }).selectOption('cm')
      assert.match(await areaRow.locator('dd').innerText(), /cm²/)
      await result.getByLabel('Display unit', { exact: true }).selectOption('mm')
      await moduleTab.setViewportSize({ width: 390, height: 844 })
      assert.ok(await moduleTab.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${code} Section Properties overflows on mobile`)
      await moduleTab.setViewportSize({ width: 1440, height: 1100 })
    }
    await moduleTab.goto(new URL('#/modules/analysis', base).href)
    await moduleTab.locator('.section-properties-panel').waitFor({ state: 'visible' })
    assert.equal(await moduleTab.locator('.module-navigation a[href$="/modules/analysis"]').count(), 0, 'Legacy bookmark stays usable without restoring a navigation item')
    await moduleTab.locator('.module-navigation a[href$="/modules/library"]').click()
    await moduleTab.getByText('Read only', { exact: true }).waitFor()
    await moduleTab.reload()
    await moduleTab.getByText('Read only', { exact: true }).waitFor()
    await moduleTab.getByRole('button', { name: 'Sign out', exact: true }).click()
    await page.getByRole('heading', { name: 'Sign in', exact: true }).waitFor()
    await moduleTab.getByRole('heading', { name: 'Sign in', exact: true }).waitFor()
    await moduleTab.close()
    await signIn(page, { demo, role: 'admin' })
    await page.getByRole('button', { name: /Admin interface/ }).click()
    await navyHover(page.getByRole('tab', { name: 'Materials', exact: true }))
    await navyHover(page.getByRole('tab', { name: 'Users', exact: true }))
    assert.equal(errors.length, 0, errors.join('\n'))
    console.log(`${demo ? 'Demo' : 'Laravel'} module checks passed: uploaded cover bytes/MIME, navy/white hover in both interfaces, new browser tab with shared login and no opener, five-module navigation, nine illustrated Component buttons and keyboard/selection state, 53 illustrated Connection workspaces in two groups, reference integrity, search and keyboard/group memory, VI/EN state, placeholders, read-only library, direct reload, cross-tab logout, mobile.`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
