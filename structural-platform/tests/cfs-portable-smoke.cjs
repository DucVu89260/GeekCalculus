const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/opt/codex/cua_node/lib/node_modules/playwright')
const { signIn } = require('./browser-auth.cjs')
const base = process.env.CFS_BASE_URL || 'http://127.0.0.1:5173/'

;(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'geek-cfs-smoke-'))
  execFileSync(process.env.ENGINE_PYTHON || 'python3', [path.join(__dirname, 'cfs/fixtures.py'), directory])
  const original = fs.readFileSync(path.join(directory, 'synthetic.cfsa'))
  const offsets = JSON.parse(fs.readFileSync(path.join(directory, 'offsets.json')))
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' })
    await context.addInitScript(() => localStorage.setItem('geekcalculus-locale', 'en'))
    const page = await context.newPage()
    const errors = []
    const uploads = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base)
    await signIn(page, { demo: process.env.TEST_DEMO === '1', role: 'user' })
    await page.goto(new URL('#/modules/steel/cfs', base).href)
    await page.locator('.cfs-card').click()
    assert.ok(page.url().endsWith('#/modules/steel/cfs/lapping-node'))
    context.on('request', request => { if (request.method() !== 'GET') uploads.push(request.url()) })
    const frame = page.frameLocator('iframe[title="CFS Lapping and Node Add-in"]')
    const ready = async () => {
      await frame.locator('[data-cfs-locale="vi"]').click()
      await frame.locator('#runtime-status').filter({ hasText: 'Python sẵn sàng' }).waitFor({ timeout: 60000 })
      assert.equal(await page.locator('.module-actions button[aria-pressed="true"]').innerText(), 'VI')
    }
    const pickSource = async () => {
      const chooser = page.waitForEvent('filechooser')
      await frame.locator('#chooseFile').click()
      await (await chooser).setFiles(path.join(directory, 'synthetic.cfsa'))
    }
    const pickSections = async () => {
      const chooser = page.waitForEvent('filechooser')
      await frame.locator('#chooseSections').click()
      await (await chooser).setFiles(path.join(directory, 'SECTIONS'))
    }
    const importModel = async () => {
      await frame.locator('#import').click()
      await frame.locator('#kpi b').first().waitFor()
      await frame.locator('#cfs-busy').waitFor({ state: 'hidden' })
    }
    const downloadCopy = async () => {
      page.once('dialog', dialog => dialog.accept())
      const event = page.waitForEvent('download')
      await frame.locator('#applyTest').click()
      const download = await event
      assert.equal(download.suggestedFilename(), 'synthetic_WEBTEST.cfsa')
      const data = fs.readFileSync(await download.path())
      await frame.locator('#status').filter({ hasText: /(?:không đổi|unchanged): true/ }).waitFor()
      assert.equal(fs.readFileSync(path.join(directory, 'synthetic.cfsa')).equals(original), true)
      return data
    }
    await frame.locator('[data-cfs-locale="en"][aria-pressed="true"]').waitFor()
    assert.equal(await frame.locator('#unit-note').innerText(), 'Units: m- kN')
    assert.match(await frame.locator('#json-import-help').innerText(), /restore a draft/)
    assert.match(await frame.locator('#json-export-help').innerText(), /back it up/)
    await ready()
    assert.equal(await frame.locator('#unit-note').innerText(), 'Đơn vị: m- kN')
    await pickSource()
    await pickSections()
    await importModel()
    assert.match(await frame.locator('#figure').textContent(), /-1\.000 → 13\.000/)
    await frame.locator('[data-joint="0"][role="button"]').focus()
    await page.keyboard.press('Enter')
    const left = frame.locator('[data-kind="lap-left"][data-i="0"]')
    await left.fill('0.8'); await left.press('Tab')
    const right = frame.locator('[data-kind="lap-right"][data-i="0"]')
    await right.fill('0.9'); await right.press('Tab')
    const expected = Buffer.from(original)
    expected.writeFloatLE(6.9 / 0.0254, offsets.member_offsets[0] + 4)
    expected.writeFloatLE(5.2 / 0.0254, offsets.member_offsets[1])
    // Language switches update presentation in place, not the model or iframe URL.
    const frameUrl = await page.locator('iframe').getAttribute('src')
    const exportJson = async () => {
      const event = page.waitForEvent('download')
      await frame.locator('#export').click()
      return JSON.parse(fs.readFileSync(await (await event).path(), 'utf8'))
    }
    const beforeLanguage = await exportJson()
    for (let i = 0; i < 2; i++) {
      await frame.locator('[data-cfs-locale="en"]').click()
      await page.locator('.module-actions button[aria-pressed="true"]').filter({ hasText: 'EN' }).waitFor()
      assert.equal(await frame.locator('#unit-note').innerText(), 'Units: m- kN')
      assert.match(await frame.locator('#editor').innerText(), /Each side is independent/)
      assert.equal(await left.inputValue(), '0.800')
      assert.equal(await right.inputValue(), '0.900')
      assert.deepEqual(await exportJson(), beforeLanguage)
      await page.locator('.module-actions').getByRole('button', { name: 'VI', exact: true }).click()
      await frame.locator('html[lang="vi"]').waitFor()
      assert.equal(await frame.locator('#unit-note').innerText(), 'Đơn vị: m- kN')
      assert.deepEqual(await exportJson(), beforeLanguage)
    }
    assert.equal(await page.locator('iframe').getAttribute('src'), frameUrl)
    assert.deepEqual(await downloadCopy(), expected)
    await frame.locator('#saveDraft').click()
    await frame.locator('#status').filter({ hasText: 'Đã lưu bản nháp' }).waitFor()
    await page.reload()
    await ready()
    await frame.locator('#loadDraft').click()
    await frame.locator('#status').filter({ hasText: 'Đã tải bản nháp' }).waitFor()
    assert.equal(await frame.locator('[data-kind="lap-left"][data-i="0"]').inputValue(), '0.800')
    page.once('dialog', dialog => dialog.accept())
    await frame.locator('#applyTest').click()
    await frame.locator('#status').filter({ hasText: 'Import lại CFSA' }).waitFor()
    // Missing SECTIONS cannot silently pass export; reselect then restore draft.
    await pickSource()
    await importModel()
    await frame.locator('#sections .bad').filter({ hasText: 'Không tìm thấy tiết diện' }).waitFor()
    await frame.locator('#applyTest').click()
    await frame.locator('#status').filter({ hasText: 'Thiếu Section' }).waitFor()
    await pickSections()
    await importModel()
    await frame.locator('#loadDraft').click()
    await frame.locator('#status').filter({ hasText: 'Đã tải bản nháp' }).waitFor()
    const jsonEvent = page.waitForEvent('download')
    await frame.locator('#export').click()
    const json = JSON.parse(fs.readFileSync(await (await jsonEvent).path(), 'utf8'))
    assert.equal(json.members[0].end_m, 6.9)
    assert.equal(json.members[1].start_m, 5.2)
    assert.equal('combinations' in json, false)
    await frame.locator('[data-tab="supports"]').click()
    const mainSupport = frame.locator('[data-support-row="0"] input')
    assert.equal(await mainSupport.isDisabled(), true)
    await frame.locator('#autoN').fill('3')
    await frame.locator('#previewAuto').click()
    await frame.locator('#applyAuto').click()
    assert.equal(await frame.locator('#kpi b').nth(2).innerText(), '7')
    const inserted = await downloadCopy()
    assert.equal(inserted[offsets.count_offset], 7)
    assert.equal(inserted.length, original.length + 30)
    assert.deepEqual(inserted.subarray(offsets.combination_offset + 30), original.subarray(offsets.combination_offset))
    await frame.locator('#autoN').fill('0')
    await frame.locator('#applyAuto').click()
    const deleted = await downloadCopy()
    assert.equal(deleted[offsets.count_offset], 4)
    assert.equal(deleted.length, original.length - 15)
    assert.deepEqual(deleted.subarray(offsets.combination_offset - 15), original.subarray(offsets.combination_offset))
    const afterEditing = await exportJson()
    await frame.locator('[data-cfs-locale="en"]').click()
    await frame.locator('html[lang="en"]').waitFor()
    assert.ok(!/[ăâđêôơư\u1ea0-\u1ef9]/i.test(await frame.locator('body').innerText()), 'English CFS view contains untranslated Vietnamese')
    assert.deepEqual(await exportJson(), afterEditing)
    await frame.locator('[data-cfs-locale="vi"]').click()
    await frame.locator('html[lang="vi"]').waitFor()
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Parent overflow at ${width}`)
      assert.ok(await frame.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth), `CFS overflow at ${width}`)
    }
    await page.setViewportSize({ width: 1440, height: 1100 })
    await page.waitForFunction(() => {
      const frame = document.querySelector('iframe[title="CFS Lapping and Node Add-in"]')
      const content = frame?.contentDocument?.body?.getBoundingClientRect().height
      return content && frame.clientHeight < content + 100
    })
    if (process.env.CFS_SCREENSHOT_PATH) await page.screenshot({ path: process.env.CFS_SCREENSHOT_PATH, fullPage: true })
    assert.deepEqual(uploads, [], 'CFSA/sections/drafts must never be uploaded to a server')
    assert.deepEqual(errors, [])
    console.log('PASS: real browser Python, CFSA/SECTIONS import, negative domain, lap byte parity, draft/reload/source gate, missing sections, XT insert/delete, immutable originals/combinations, mobile, no uploads')
  } finally { await browser.close(); fs.rmSync(directory, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
