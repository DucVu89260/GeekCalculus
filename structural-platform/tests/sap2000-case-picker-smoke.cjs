// UI-only case catalog: no real SAP2000 model or output settings are changed.
const assert=require('node:assert/strict')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
;(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  const longName='ENVE_'+('1.2D+1.2MEDL+1.2COLL+0.5LR+1.6WX1+_').repeat(6)
  const catalog=[{name:'CASE_A',kind:'case'},{name:longName,kind:'combination'},
    {name:'CASE_B',kind:'case'},{name:'ENVE_2',kind:'combination'},
    {name:'ENVE_3',kind:'combination'},{name:'CASE_C',kind:'case',results_available:false},
    {name:'ENVE_4',kind:'combination'},{name:'DUPLICATE',kind:'case'},
    {name:'DUPLICATE',kind:'combination'}]
  await page.request.put('http://127.0.0.1:8011/API_IF_SAP26.2.0_V1/connection',{
   headers:{Authorization:'Bearer sap-panel-browser-test-token-00000001'},data:{pid:null}})
  await page.route('**/output-cases',route=>route.fulfill({json:{data:catalog}}))
  await page.goto('http://127.0.0.1:8011/#token=sap-panel-browser-test-token-00000001')
  await page.waitForFunction(()=>document.querySelectorAll('#instance option').length===4&&!document.querySelector('#controls').disabled)
  await page.selectOption('#instance','20948');await page.click('#connect')
  await page.waitForFunction(()=>document.querySelectorAll('#cases label').length===9&&!document.querySelector('#controls').disabled)
  assert.ok((await page.locator('#outputs-panel').boundingBox()).width>=300)
  await page.selectOption('#case-kind','combination')
  const labels=page.locator('#cases label'),inputs=labels.locator('input')
  assert.equal(await labels.count(),5)
  await inputs.nth(0).check()
  await labels.nth(2).locator('span').click({modifiers:['Shift']})
  assert.equal(await page.locator('#cases input:checked').count(),3,'Shift+label selects visible inclusive range')
  await inputs.nth(2).click({modifiers:['Shift']})
  assert.equal(await page.locator('#cases input:checked').count(),0,'Shift unchecks the range')
  await inputs.nth(0).check()
  await inputs.nth(2).focus();await inputs.nth(2).press('Shift+Space')
  assert.equal(await page.locator('#cases input:checked').count(),3,'Keyboard Shift+Space range selection')
  await inputs.nth(2).press('Shift+Space')
  assert.equal(await page.locator('#cases input:checked').count(),0)
  await inputs.nth(3).check()
  await inputs.nth(1).click({modifiers:['Shift']})
  assert.equal(await page.locator('#cases input:checked').count(),3,'Reverse range selection')
  await page.selectOption('#case-kind','case')
  assert.equal(await page.locator('#cases input:checked').count(),0,'Hidden cases were not included in combo range')
  await page.click('#select-all')
  assert.equal(await page.locator('#cases input:checked').count(),4)
  assert.match(await page.locator('#case-count').textContent(),/7 \/ 9/)
  await page.fill('#search','case_b')
  assert.equal(await labels.count(),1);assert.equal(await inputs.nth(0).isChecked(),true)
  await page.click('#select-none')
  await page.fill('#search','');await page.selectOption('#case-kind','combination')
  assert.equal(await page.locator('#cases input:checked').count(),0,'Clear all includes hidden selections')
  await page.fill('#search','enve')
  assert.equal(await labels.count(),4)
  await inputs.nth(0).click({modifiers:['Shift']})
  assert.equal(await page.locator('#cases input:checked').count(),1,'Filter changes reset Shift anchor')
  await page.fill('#search','');await page.selectOption('#case-kind','')
  assert.equal(await labels.count(),9)
  const longLabel=labels.filter({hasText:longName})
  assert.equal(await longLabel.getAttribute('title'),longName)
  await longLabel.locator('input').hover()
  assert.equal(await page.locator('#case-preview').textContent(),'Combo: '+longName)
  const overflow=await page.locator('#cases').evaluate(el=>{el.scrollLeft=el.scrollWidth;return {overflow:el.scrollWidth>el.clientWidth,scrolled:el.scrollLeft>0,mode:getComputedStyle(el).overflowX}})
  assert.deepEqual(overflow,{overflow:true,scrolled:true,mode:'scroll'})
  await page.locator('#cases').evaluate(el=>el.scrollLeft=0)
  await page.screenshot({path:'/tmp/sap-case-picker-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.screenshot({path:'/tmp/sap-case-picker-mobile.png',fullPage:true})
  assert.deepEqual(errors,[])
  console.log('Case picker passed: Shift select/unselect/reverse, type+name filters, hidden selections, anchor reset, full-name hover, horizontal scroll, wider sidebar and mobile.')
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
